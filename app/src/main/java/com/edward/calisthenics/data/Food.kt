package com.edward.calisthenics.data

enum class Meal(val title: String) {
    BREAKFAST("Завтрак"),
    LUNCH("Обед"),
    SNACK("Перекус"),
    DINNER("Ужин"),
}

/** Продукт рецепта: по-русски, по-вьетнамски (показать продавцу) и сколько нужно. */
data class Ing(val ru: String, val vn: String, val amount: String = "")

data class Recipe(
    val id: String,
    val name: String,
    /** Название блюда по-вьетнамски. */
    val vn: String,
    val kcal: Int,
    val protein: Int,
    val minutes: Int,
    val ingredients: List<Ing>,
    val steps: List<String>,
    /** Еда вне дома: примерная цена. */
    val outside: String? = null,
    val tip: String? = null,
)

data class MenuDay(val breakfast: String, val lunch: String, val snack: String, val dinner: String) {
    fun ids() = listOf(Meal.BREAKFAST to breakfast, Meal.LUNCH to lunch, Meal.SNACK to snack, Meal.DINNER to dinner)
}

/** Пункт покупок. ask — что сказать или показать продавцу по-вьетнамски. */
data class ShopItem(val id: String, val name: String, val local: String, val amount: String, val price: String, val ask: String = "")

/** Продукт из справочника: калории и белок на 100 г (или на штуку), как выбрать и сколько хранить. */
data class Product(val ru: String, val vn: String, val kcal: Int, val protein: Double, val per: String, val price: String, val choose: String, val keep: String)

data class ProductGroup(val title: String, val items: List<Product>)

data class ShopGroup(val title: String, val note: String, val items: List<ShopItem>)


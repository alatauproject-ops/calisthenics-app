    private fun chain(
        id: String,
        title: String,
        emoji: String,
        levelStarts: List<Int>,
        vararg steps: StepDef,
    ) = Chain(
        id = id,
        title = title,
        emoji = emoji,
        levelStarts = levelStarts,
        steps = steps.mapIndexed { i, s ->
            Exercise("$id-$i", id, i, s.name, s.measure, s.start, s.goal, s.cues)
        },
    )

    private class StepDef(
        val name: String,
        val measure: Measure,
        val start: Int,
        val goal: Int,
        val cues: String,
    )

    private fun reps(name: String, start: Int, goal: Int, cues: String) = StepDef(name, REPS, start, goal, cues)
    private fun hold(name: String, start: Int, goal: Int, cues: String) = StepDef(name, HOLD, start, goal, cues)


    private val byId: Map<String, Exercise> = chains.flatMap { it.steps }.associateBy { it.id }
    private val chainById: Map<String, Chain> = chains.associateBy { it.id }

    fun exercise(id: String): Exercise? = byId[id]
    fun chain(id: String): Chain? = chainById[id]


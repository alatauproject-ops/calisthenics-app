    fun defaultProgress(level: Level): Map<String, ChainProgress> =
        chains.associate { c ->
            val step = c.levelStarts[level.ordinal].coerceIn(0, c.steps.lastIndex)
            c.id to ChainProgress(step, c.steps[step].startTarget)
        }
